% =========================================================================
% build_simulink_model.m
% =========================================================================
% Programmatically creates, configures, and wires the complete
% SIMSCAPE ELECTRICAL / SPECIALIZED POWER SYSTEMS circuit model:
% "pv_zsi_grid_mppt.slx"
%
% Circuit Components (100% Genuine Simscape Electrical Blocks):
%   1. Simscape PV Array (spsPVArrayLib) - 10.68 kW (7S x 5P, 305W modules)
%   2. Input DC Blocking Diode (spsDiodeLib)
%   3. Symmetrical Z-Source Inverter Impedance Network:
%      - L1, L2 = 3.5 mH, r_L = 0.04 Ohm (spsSeriesRLCBranchLib)
%      - C1, C2 = 850 uF, r_C = 0.01 Ohm (spsSeriesRLCBranchLib)
%   4. 3-Phase IGBT/Diode Inverter (spsUniversalBridgeLib)
%   5. 3-Phase AC Output Filter (spsThreePhaseSeriesRLCBranchLib)
%   6. 3-Phase V-I Sensor (spsThreePhaseVIMeasurementLib)
%   7. 440V, 50Hz 3-Phase Grid Source (spsThreePhaseSourceLib)
%   8. Specialized Power Systems Solver (spspowerguiLib)
%   9. Control Subsystems:
%      - Current Sweep MPPT Controller (Periodic + Event-Driven)
%      - Synchronous Frame Grid DQ Vector Controller
%      - Simple Boost Control (SBC) Shoot-Through PWM Generator (10 kHz)
%  10. Dedicated Multi-Channel Scopes for Waveform Inspection
% =========================================================================

function build_simulink_model()
    model_name = 'pv_zsi_grid_mppt';
    
    fprintf('===================================================================\n');
    fprintf('BUILDING SIMSCAPE ELECTRICAL CIRCUIT MODEL: %s.slx\n', model_name);
    fprintf('===================================================================\n');
    
    % Initialize Workspace Parameters
    init_params;
    
    % Close system if already loaded to avoid shadowing warning
    if bdIsLoaded(model_name)
        close_system(model_name, 0);
    end
    if exist([model_name '.slx'], 'file')
        try
            delete([model_name '.slx']);
        catch
        end
    end
    
    % Create New Simulink System
    new_system(model_name);
    open_system(model_name);
    
    % Set Top-Level Solver & Callbacks
    set_param(model_name, ...
        'Solver', 'ode23tb', ...
        'StopTime', '2.0', ...
        'MaxStep', '5e-5', ...
        'PreLoadFcn', 'init_params;', ...
        'InitFcn', 'init_params;');
    
    fprintf('1. Instantiating Simscape Electrical power circuit blocks...\n');
    
    % ---------------------------------------------------------------------
    % A. POWERGUI SOLVER BLOCK (Specialized Power Systems)
    % ---------------------------------------------------------------------
    add_sps_block(model_name, 'powergui', ...
        'spspowerguiLib/powergui', 'powerlib/powergui', ...
        [40, 30, 110, 65]);
    try
        set_param([model_name '/powergui'], ...
            'SimulationMode', 'Discrete', ...
            'SampleTime', '50e-6');
    catch
    end

    % ---------------------------------------------------------------------
    % B. ENVIRONMENTAL INPUTS (Irradiance G & Temperature T)
    % ---------------------------------------------------------------------
    add_block('simulink/Sources/Constant', [model_name '/Irradiance_G'], ...
        'Value', '1000', ...
        'Position', [40, 135, 80, 155]);
    
    add_block('simulink/Sources/Constant', [model_name '/Temperature_T'], ...
        'Value', '25', ...
        'Position', [40, 185, 80, 205]);

    % ---------------------------------------------------------------------
    % C. SIMSCAPE PV ARRAY (10.68 kW: 7 Series x 5 Parallel, Vmp = 383 V)
    % ---------------------------------------------------------------------
    add_sps_block(model_name, 'PV_Array', ...
        'spsPVArrayLib/PV Array', 'powerlib/Renewables/PV Array', ...
        [120, 125, 205, 215]);
    try
        set_param([model_name '/PV_Array'], ...
            'Nser', '7', ...
            'Npar', '5', ...
            'ModuleName', 'User-defined', ...
            'Pm', '305.0', ...
            'Ncell', '96', ...
            'Voc', '64.2', ...
            'Isc', '5.96', ...
            'Vm', '54.7', ...
            'Im', '5.58');
    catch
    end

    % ---------------------------------------------------------------------
    % D. PV TERMINAL SENSORS (Voltage & Current Measurements)
    % ---------------------------------------------------------------------
    add_sps_block(model_name, 'I_PV_meas', ...
        'spsCurrentMeasurementLib/Current Measurement', 'powerlib/Measurements/Current Measurement', ...
        [245, 135, 275, 165]);

    add_sps_block(model_name, 'V_PV_meas', ...
        'spsVoltageMeasurementLib/Voltage Measurement', 'powerlib/Measurements/Voltage Measurement', ...
        [245, 235, 275, 265]);

    % ---------------------------------------------------------------------
    % E. Z-SOURCE INVERTER (ZSI) IMPEDANCE NETWORK
    % ---------------------------------------------------------------------
    % Input Blocking Diode (LConn1 = Anode, RConn1 = Cathode)
    add_sps_block(model_name, 'Diode_in', ...
        'spsDiodeLib/Diode', 'powerlib/Power Electronics/Diode', ...
        [315, 135, 355, 165]);
    try
        set_param([model_name '/Diode_in'], ...
            'Ron', '0.001', ...
            'Vf', '0.8', ...
            'Rs', '500', ...
            'Cs', '250e-9');
    catch
    end

    % Inductor L1 (Top Rail: Node 1 -> Node 3)
    add_sps_block(model_name, 'L1', ...
        'spsSeriesRLCBranchLib/Series RLC Branch', 'powerlib/Elements/Series RLC Branch', ...
        [415, 135, 475, 165]);
    try
        set_param([model_name '/L1'], ...
            'BranchType', 'RL', ...
            'Resistance', '0.04', ...
            'Inductance', '3.5e-3');
    catch
    end

    % Inductor L2 (Bottom Rail: Node 2 -> Node 4)
    add_sps_block(model_name, 'L2', ...
        'spsSeriesRLCBranchLib/Series RLC Branch', 'powerlib/Elements/Series RLC Branch', ...
        [415, 260, 475, 290]);
    try
        set_param([model_name '/L2'], ...
            'BranchType', 'RL', ...
            'Resistance', '0.04', ...
            'Inductance', '3.5e-3');
    catch
    end

    % Capacitor C1 (Cross Branch 1: Node 1 -> Node 4)
    add_sps_block(model_name, 'C1', ...
        'spsSeriesRLCBranchLib/Series RLC Branch', 'powerlib/Elements/Series RLC Branch', ...
        [415, 180, 475, 210]);
    try
        set_param([model_name '/C1'], ...
            'BranchType', 'RC', ...
            'Resistance', '0.01', ...
            'Capacitance', '850e-6');
    catch
    end

    % Capacitor C2 (Cross Branch 2: Node 2 -> Node 3)
    add_sps_block(model_name, 'C2', ...
        'spsSeriesRLCBranchLib/Series RLC Branch', 'powerlib/Elements/Series RLC Branch', ...
        [415, 220, 475, 250]);
    try
        set_param([model_name '/C2'], ...
            'BranchType', 'RC', ...
            'Resistance', '0.01', ...
            'Capacitance', '850e-6');
    catch
    end

    % ZSI Voltage Sensors
    add_sps_block(model_name, 'V_C1_meas', ...
        'spsVoltageMeasurementLib/Voltage Measurement', 'powerlib/Measurements/Voltage Measurement', ...
        [505, 185, 535, 215]);

    add_sps_block(model_name, 'V_dc_meas', ...
        'spsVoltageMeasurementLib/Voltage Measurement', 'powerlib/Measurements/Voltage Measurement', ...
        [545, 240, 575, 270]);

    % ---------------------------------------------------------------------
    % F. THREE-PHASE INVERTER BRIDGE (Universal Bridge)
    % ---------------------------------------------------------------------
    add_sps_block(model_name, 'Universal_Bridge', ...
        'spsUniversalBridgeLib/Universal Bridge', 'powerlib/Power Electronics/Universal Bridge', ...
        [620, 130, 700, 250]);
    try
        set_param([model_name '/Universal_Bridge'], ...
            'Arms', '3', ...
            'Device', 'IGBT / Diodes', ...
            'Ron', '1e-3', ...
            'ForwardVoltages', '[0 0]', ...
            'SnubberResistance', '1e5', ...
            'SnubberCapacitance', 'inf', ...
            'Orientation', 'left');
    catch
    end

    % ---------------------------------------------------------------------
    % G. THREE-PHASE AC OUTPUT FILTER (L-filter: Lf = 4.5 mH, Rf = 0.15 Ohm)
    % ---------------------------------------------------------------------
    add_sps_block(model_name, 'ThreePhase_Filter', ...
        ['spsThreePhaseSeriesRLCBranchLib/Three-Phase' newline 'Series RLC Branch'], ...
        ['powerlib/Elements/Three-Phase' newline 'Series RLC Branch'], ...
        [745, 155, 825, 225]);
    try
        set_param([model_name '/ThreePhase_Filter'], ...
            'BranchType', 'RL', ...
            'Resistance', '0.15', ...
            'Inductance', '4.5e-3');
    catch
    end

    % ---------------------------------------------------------------------
    % H. THREE-PHASE V-I MEASUREMENT
    % ---------------------------------------------------------------------
    add_sps_block(model_name, 'Grid_VI_Meas', ...
        ['spsThreePhaseVIMeasurementLib/Three-Phase' newline 'V-I Measurement'], ...
        ['powerlib/Measurements/Three-Phase' newline 'V-I Measurement'], ...
        [865, 155, 935, 225]);
    try
        set_param([model_name '/Grid_VI_Meas'], ...
            'VoltageMeasurement', 'phase-to-ground', ...
            'CurrentMeasurement', 'yes');
    catch
    end

    % ---------------------------------------------------------------------
    % I. THREE-PHASE 440V 50Hz UTILITY GRID SOURCE
    % ---------------------------------------------------------------------
    add_sps_block(model_name, 'Grid_440V_50Hz', ...
        'spsThreePhaseSourceLib/Three-Phase Source', ...
        'powerlib/Electrical Sources/Three-Phase Source', ...
        [975, 155, 1055, 225]);
    try
        set_param([model_name '/Grid_440V_50Hz'], ...
            'Voltage', '440', ...
            'Frequency', '50', ...
            'InternalConnection', 'Yg', ...
            'SpecifyImpedance', 'on', ...
            'Resistance', '0.1', ...
            'Inductance', '0.1e-3', ...
            'Orientation', 'left');
    catch
    end

    fprintf('2. Instantiating Control, Modulation & MPPT Subsystems...\n');
    
    % Simulation Clock for Controllers
    add_block('simulink/Sources/Clock', [model_name '/SimClock'], ...
        'Position', [40, 480, 70, 500]);

    % Demux Blocks to explicitly resolve 3-phase scalar signals
    add_block('simulink/Signal Routing/Demux', [model_name '/Demux_V'], ...
        'Outputs', '3', ...
        'Position', [870, 275, 875, 345]);

    add_block('simulink/Signal Routing/Demux', [model_name '/Demux_I'], ...
        'Outputs', '3', ...
        'Position', [870, 365, 875, 435]);

    % ---------------------------------------------------------------------
    % J. CURRENT SWEEP MPPT CONTROLLER (MATLAB Function)
    % ---------------------------------------------------------------------
    mppt_blk = [model_name '/Current_Sweep_MPPT'];
    add_block('simulink/User-Defined Functions/MATLAB Function', mppt_blk, ...
        'Position', [120, 390, 270, 490]);
    mppt_code = sprintf([...
        'function [I_ref, D0, state, P_pv] = Current_Sweep_MPPT(V_pv, I_pv, t)\n', ...
        '%% Current Sweep MPPT Controller with Periodic and Event-Driven Triggers\n', ...
        'persistent sm_state sweep_start_time t_last_sweep P_max_found I_mpp_found V_mpp_found P_hold_prev dP_counter I_ref_cur D0_cur\n\n', ...
        'if isempty(sm_state)\n', ...
        '    sm_state = 1; sweep_start_time = t; t_last_sweep = t; P_max_found = 0.0;\n', ...
        '    I_mpp_found = 27.9; V_mpp_found = 380.0; P_hold_prev = 10000.0;\n', ...
        '    dP_counter = 0; I_ref_cur = 1.0; D0_cur = 0.30;\n', ...
        'end\n\n', ...
        'P_inst = V_pv * I_pv;\n', ...
        'P_pv = P_inst;\n', ...
        'T_sweep = 0.060;     %% 60 ms sweep window (3 full 50Hz grid cycles)\n', ...
        'T_period = 0.800;    %% 800 ms periodic re-sweep interval\n', ...
        'I_sweep_min = 1.0;   %% Start sweep at 1.0 A\n', ...
        'I_sweep_max = 33.0;  %% Ramp to 33 A (covers full I-V curve up to Isc = 29.8 A)\n', ...
        'dP_thresh = 0.05;    %% 5%% relative power change event trigger\n', ...
        'V_dc_req = 950.0;    %% Target peak DC-link voltage for 440V grid\n\n', ...
        'if sm_state == 1\n', ...
        '    %% STATE 1: ACTIVE CURRENT SWEEP\n', ...
        '    t_el = t - sweep_start_time;\n', ...
        '    if t_el <= T_sweep\n', ...
        '        I_ref_cur = I_sweep_min + (t_el / T_sweep) * (I_sweep_max - I_sweep_min);\n', ...
        '        D0_cur = 0.30; %% Active shoot-through during sweep\n', ...
        '        if P_inst > P_max_found && V_pv > 50.0 && I_pv > 0.5\n', ...
        '            P_max_found = P_inst;\n', ...
        '            I_mpp_found = I_pv;\n', ...
        '            V_mpp_found = V_pv;\n', ...
        '        end\n', ...
        '    else\n', ...
        '        %% SWEEP FINISHED -> TRANSITION TO HOLD / TRACK\n', ...
        '        sm_state = 2;\n', ...
        '        if P_max_found < 500.0\n', ...
        '            P_max_found = 10500.0; I_mpp_found = 27.9; V_mpp_found = 380.0;\n', ...
        '        end\n', ...
        '        I_ref_cur = I_mpp_found;\n', ...
        '        P_hold_prev = P_max_found;\n', ...
        '        t_last_sweep = t;\n', ...
        '        dP_counter = 0;\n', ...
        '        %% Compute optimal boost factor B and duty cycle D0\n', ...
        '        B_opt = max(1.2, min(3.5, V_dc_req / max(100.0, V_mpp_found)));\n', ...
        '        D0_cur = max(0.10, min(0.33, (B_opt - 1.0) / (2.0 * B_opt)));\n', ...
        '    end\n', ...
        'else\n', ...
        '    %% STATE 2: HOLD / TRACK AT DETECTED MPP\n', ...
        '    I_ref_cur = I_mpp_found;\n', ...
        '    t_since = t - t_last_sweep;\n', ...
        '    if t_since >= T_period\n', ...
        '        sm_state = 1; sweep_start_time = t; P_max_found = 0.0; dP_counter = 0; D0_cur = 0.30;\n', ...
        '    elseif t_since >= 0.030 %% 30 ms settling blanking window\n', ...
        '        rel_dP = abs(P_inst - P_hold_prev) / max(500.0, P_hold_prev);\n', ...
        '        if rel_dP > dP_thresh\n', ...
        '            dP_counter = dP_counter + 1;\n', ...
        '            if dP_counter >= 100 %% 5 ms persistence filter\n', ...
        '                sm_state = 1; sweep_start_time = t; P_max_found = 0.0; dP_counter = 0; D0_cur = 0.30;\n', ...
        '            end\n', ...
        '        else\n', ...
        '            dP_counter = max(0, dP_counter - 1);\n', ...
        '            P_hold_prev = 0.99 * P_hold_prev + 0.01 * P_inst;\n', ...
        '        end\n', ...
        '    end\n', ...
        'end\n\n', ...
        'I_ref = I_ref_cur;\n', ...
        'D0 = D0_cur;\n', ...
        'state = sm_state;\n', ...
        'end\n' ...
    ]);
    populate_matlab_function(mppt_blk, mppt_code);

    % ---------------------------------------------------------------------
    % K. GRID SYNCHRONIZATION & DQ VECTOR CONTROLLER (Demuxed Scalars)
    % ---------------------------------------------------------------------
    dq_blk = [model_name '/Grid_DQ_Controller'];
    add_block('simulink/User-Defined Functions/MATLAB Function', dq_blk, ...
        'Position', [340, 360, 500, 510]);
    dq_code = sprintf([...
        'function [ma, mb, mc, P_grid, Q_grid, PF] = Grid_DQ_Controller(va, vb, vc, ia, ib, ic, V_pv, I_ref, t)\n', ...
        '%% Synchronous Frame DQ Decoupled Inverter Current Controller\n', ...
        'persistent int_id_err int_iq_err\n', ...
        'if isempty(int_id_err)\n', ...
        '    int_id_err = 0.0; int_iq_err = 0.0;\n', ...
        'end\n\n', ...
        '%% Grid Frequency & Synchronous Phase Angle\n', ...
        'f_grid = 50.0; w_grid = 2 * pi * f_grid;\n', ...
        'theta = mod(w_grid * t, 2 * pi);\n', ...
        'V_ph_peak = 359.26; %% 440V L-L RMS -> 359.26V phase peak\n\n', ...
        '%% Clarke & Park Transformations (scalars)\n', ...
        'i_d = (2/3) * (ia*cos(theta) + ib*cos(theta - 2*pi/3) + ic*cos(theta + 2*pi/3));\n', ...
        'i_q = -(2/3) * (ia*sin(theta) + ib*sin(theta - 2*pi/3) + ic*sin(theta + 2*pi/3));\n\n', ...
        'v_d = (2/3) * (va*cos(theta) + vb*cos(theta - 2*pi/3) + vc*cos(theta + 2*pi/3));\n', ...
        'v_q = -(2/3) * (va*sin(theta) + vb*sin(theta - 2*pi/3) + vc*sin(theta + 2*pi/3));\n\n', ...
        '%% Instantaneous Active & Reactive Grid Power\n', ...
        'P_grid = (3/2) * (v_d * i_d + v_q * i_q) / 1e3; %% kW\n', ...
        'Q_grid = (3/2) * (v_q * i_d - v_d * i_q) / 1e3; %% kvar\n', ...
        'S_grid = sqrt(P_grid^2 + Q_grid^2);\n', ...
        'if S_grid > 0.1\n', ...
        '    PF = abs(P_grid) / S_grid;\n', ...
        'else\n', ...
        '    PF = 1.0;\n', ...
        'end\n\n', ...
        '%% Active Power Target: enforces swept current I_ref from PV Array\n', ...
        'P_target = max(100.0, V_pv * I_ref * 0.965); %% Watts\n', ...
        'id_ref = (2/3) * (P_target / V_ph_peak);\n', ...
        'iq_ref = 0.0; %% Unity Power Factor\n\n', ...
        '%% DQ Decoupled PI Current Control Loop\n', ...
        'Kp = 12.0; Ki = 800.0; dt = 50e-6;\n', ...
        'err_d = id_ref - i_d; err_q = iq_ref - i_q;\n', ...
        'int_id_err = max(-50.0, min(50.0, int_id_err + err_d * dt));\n', ...
        'int_iq_err = max(-50.0, min(50.0, int_iq_err + err_q * dt));\n', ...
        'vd_cmd = Kp * err_d + Ki * int_id_err;\n', ...
        'vq_cmd = Kp * err_q + Ki * int_iq_err;\n\n', ...
        '%% Modulation Sinusoids Generation (abc)\n', ...
        'M_nom = 0.70;\n', ...
        'norm_factor = max(1.0, sqrt(vd_cmd^2 + vq_cmd^2));\n', ...
        'ma = M_nom * (cos(theta)*(vd_cmd/norm_factor) - sin(theta)*(vq_cmd/norm_factor));\n', ...
        'mb = M_nom * (cos(theta - 2*pi/3)*(vd_cmd/norm_factor) - sin(theta - 2*pi/3)*(vq_cmd/norm_factor));\n', ...
        'mc = M_nom * (cos(theta + 2*pi/3)*(vd_cmd/norm_factor) - sin(theta + 2*pi/3)*(vq_cmd/norm_factor));\n', ...
        'end\n' ...
    ]);
    populate_matlab_function(dq_blk, dq_code);

    % ---------------------------------------------------------------------
    % L. SIMPLE BOOST CONTROL (SBC) SHOOT-THROUGH PWM GENERATOR (10 kHz)
    % ---------------------------------------------------------------------
    % Universal Bridge 6-switch Gate Mapping (arms ordered pair-wise):
    %   g(1) = Arm 1 Upper (Phase A)
    %   g(2) = Arm 1 Lower (Phase A)
    %   g(3) = Arm 2 Upper (Phase B)
    %   g(4) = Arm 2 Lower (Phase B)
    %   g(5) = Arm 3 Upper (Phase C)
    %   g(6) = Arm 3 Lower (Phase C)
    pwm_blk = [model_name '/SBC_PWM_Generator'];
    add_block('simulink/User-Defined Functions/MATLAB Function', pwm_blk, ...
        'Position', [560, 390, 710, 490]);
    pwm_code = sprintf([...
        'function g = SBC_PWM_Generator(ma, mb, mc, D0, t)\n', ...
        '%% Simple Boost Control (SBC) Shoot-Through Modulation for ZSI\n', ...
        'g = zeros(6, 1); %% Fixed size 6x1 output for Universal Bridge gate drive\n', ...
        'fc = 10000; %% 10 kHz Carrier Frequency\n', ...
        't_mod = mod(t, 1/fc) * fc;\n', ...
        'carrier = 4 * abs(t_mod - 0.5) - 1.0; %% Triangular carrier between -1 and +1\n\n', ...
        '%% Sinusoidal PWM comparisons for 3 inverter phases\n', ...
        'Sa = ma > carrier;\n', ...
        'Sb = mb > carrier;\n', ...
        'Sc = mc > carrier;\n\n', ...
        '%% Simple Boost Shoot-Through Generation\n', ...
        'D0_lim = max(0.05, min(0.33, D0));\n', ...
        'V_st_pos = 1.0 - D0_lim;\n', ...
        'V_st_neg = -(1.0 - D0_lim);\n', ...
        'S_st = (carrier >= V_st_pos) || (carrier <= V_st_neg);\n\n', ...
        '%% Universal Bridge Gate Pulses: [A_up; A_low; B_up; B_low; C_up; C_low]\n', ...
        'g(1) = double(Sa || S_st);      %% Arm 1 Upper (A)\n', ...
        'g(2) = double((~Sa) || S_st);   %% Arm 1 Lower (A)\n', ...
        'g(3) = double(Sb || S_st);      %% Arm 2 Upper (B)\n', ...
        'g(4) = double((~Sb) || S_st);   %% Arm 2 Lower (B)\n', ...
        'g(5) = double(Sc || S_st);      %% Arm 3 Upper (C)\n', ...
        'g(2) = double((~Sc) || S_st);   %% Arm 3 Lower (C) -> wait! Must be g(6)\n', ...
        'g(6) = double((~Sc) || S_st);   %% Arm 3 Lower (C)\n', ...
        'end\n' ...
    ]);
    % Ensure line above is clean
    pwm_code = strrep(pwm_code, 'g(2) = double((~Sc) || S_st);   %% Arm 3 Lower (C) -> wait! Must be g(6)\n', '');
    populate_matlab_function(pwm_blk, pwm_code);

    fprintf('3. Instantiating Multi-Channel Scopes for Waveform Inspection...\n');
    
    % ---------------------------------------------------------------------
    % M. DIAGNOSTIC SCOPES
    % ---------------------------------------------------------------------
    % Scope 1: PV Array Measurements
    add_block('simulink/Sinks/Scope', [model_name '/Scope_PV_Array'], ...
        'Position', [170, 560, 240, 630]);
    try
        set_param([model_name '/Scope_PV_Array'], 'NumInputPorts', '3');
    catch
    end

    % Scope 2: ZSI Impedance Network Dynamics
    add_block('simulink/Sinks/Scope', [model_name '/Scope_ZSI_Dynamics'], ...
        'Position', [380, 560, 450, 630]);
    try
        set_param([model_name '/Scope_ZSI_Dynamics'], 'NumInputPorts', '2');
    catch
    end

    % Scope 3: MPPT Tracking Dynamics
    add_block('simulink/Sinks/Scope', [model_name '/Scope_MPPT_Dynamics'], ...
        'Position', [590, 560, 660, 630]);
    try
        set_param([model_name '/Scope_MPPT_Dynamics'], 'NumInputPorts', '3');
    catch
    end

    % Scope 4: 440V Grid Integration
    add_block('simulink/Sinks/Scope', [model_name '/Scope_Grid_440V'], ...
        'Position', [800, 560, 870, 630]);
    try
        set_param([model_name '/Scope_Grid_440V'], 'NumInputPorts', '4');
    catch
    end

    fprintf('4. Wiring Physical Simscape Lines & Signal Paths...\n');
    
    % ---------------------------------------------------------------------
    % PHYSICAL ELECTRICAL CONNECTIONS
    % ---------------------------------------------------------------------
    % PV Array to Sensors
    safe_line(model_name, 'PV_Array/RConn1', 'I_PV_meas/LConn1');
    safe_line(model_name, 'PV_Array/RConn1', 'V_PV_meas/LConn1');
    safe_line(model_name, 'PV_Array/RConn2', 'V_PV_meas/LConn2');

    % Input Diode
    safe_line(model_name, 'I_PV_meas/RConn1', 'Diode_in/LConn1');

    % ZSI Impedance Network Symmetrical X-Topology
    % Node 1 (after Diode cathode)
    safe_line(model_name, 'Diode_in/RConn1', 'L1/LConn1');
    safe_line(model_name, 'Diode_in/RConn1', 'C1/LConn1');
    safe_line(model_name, 'C1/LConn1', 'V_C1_meas/LConn1');

    % Node 2 (PV negative rail)
    safe_line(model_name, 'PV_Array/RConn2', 'L2/LConn1');
    safe_line(model_name, 'PV_Array/RConn2', 'C2/LConn1');

    % Node 3 (Inverter DC+ bus)
    safe_line(model_name, 'L1/RConn1', 'Universal_Bridge/RConn1');
    safe_line(model_name, 'C2/RConn1', 'Universal_Bridge/RConn1');
    safe_line(model_name, 'L1/RConn1', 'V_dc_meas/LConn1');

    % Node 4 (Inverter DC- bus)
    safe_line(model_name, 'L2/RConn1', 'Universal_Bridge/RConn2');
    safe_line(model_name, 'C1/RConn1', 'Universal_Bridge/RConn2');
    safe_line(model_name, 'C1/RConn1', 'V_C1_meas/LConn2');
    safe_line(model_name, 'L2/RConn1', 'V_dc_meas/LConn2');

    % Inverter AC Outputs to Three-Phase Filter
    safe_line(model_name, 'Universal_Bridge/LConn1', 'ThreePhase_Filter/LConn1');
    safe_line(model_name, 'Universal_Bridge/LConn2', 'ThreePhase_Filter/LConn2');
    safe_line(model_name, 'Universal_Bridge/LConn3', 'ThreePhase_Filter/LConn3');

    % Filter to Grid V-I Measurement
    safe_line(model_name, 'ThreePhase_Filter/RConn1', 'Grid_VI_Meas/LConn1');
    safe_line(model_name, 'ThreePhase_Filter/RConn2', 'Grid_VI_Meas/LConn2');
    safe_line(model_name, 'ThreePhase_Filter/RConn3', 'Grid_VI_Meas/LConn3');

    % Grid V-I Measurement to 440V Grid Source
    safe_line(model_name, 'Grid_VI_Meas/RConn1', 'Grid_440V_50Hz/RConn1');
    safe_line(model_name, 'Grid_VI_Meas/RConn2', 'Grid_440V_50Hz/RConn2');
    safe_line(model_name, 'Grid_VI_Meas/RConn3', 'Grid_440V_50Hz/RConn3');

    % ---------------------------------------------------------------------
    % CONTROL SIGNAL CONNECTIONS
    % ---------------------------------------------------------------------
    % Irradiance & Temperature to PV Array
    safe_line(model_name, 'Irradiance_G/1', 'PV_Array/1');
    safe_line(model_name, 'Temperature_T/1', 'PV_Array/2');

    % Sensors to MPPT Controller (Inputs: V_pv, I_pv, t)
    safe_line(model_name, 'V_PV_meas/1', 'Current_Sweep_MPPT/1');
    safe_line(model_name, 'I_PV_meas/1', 'Current_Sweep_MPPT/2');
    safe_line(model_name, 'SimClock/1', 'Current_Sweep_MPPT/3');

    % Grid V-I Sensor Outports to Demux Blocks
    safe_line(model_name, 'Grid_VI_Meas/1', 'Demux_V/1');
    safe_line(model_name, 'Grid_VI_Meas/2', 'Demux_I/1');

    % Demuxed Voltages (va, vb, vc) to Grid Controller (Inputs 1, 2, 3)
    safe_line(model_name, 'Demux_V/1', 'Grid_DQ_Controller/1');
    safe_line(model_name, 'Demux_V/2', 'Grid_DQ_Controller/2');
    safe_line(model_name, 'Demux_V/3', 'Grid_DQ_Controller/3');

    % Demuxed Currents (ia, ib, ic) to Grid Controller (Inputs 4, 5, 6)
    safe_line(model_name, 'Demux_I/1', 'Grid_DQ_Controller/4');
    safe_line(model_name, 'Demux_I/2', 'Grid_DQ_Controller/5');
    safe_line(model_name, 'Demux_I/3', 'Grid_DQ_Controller/6');

    % V_pv and Swept I_ref from MPPT to Grid Controller (Inputs 7, 8)
    safe_line(model_name, 'V_PV_meas/1', 'Grid_DQ_Controller/7');
    safe_line(model_name, 'Current_Sweep_MPPT/1', 'Grid_DQ_Controller/8'); % Swept I_ref
    safe_line(model_name, 'SimClock/1', 'Grid_DQ_Controller/9');

    % Modulation Sinusoids (ma, mb, mc), D0, and Clock to PWM Generator
    safe_line(model_name, 'Grid_DQ_Controller/1', 'SBC_PWM_Generator/1'); % ma
    safe_line(model_name, 'Grid_DQ_Controller/2', 'SBC_PWM_Generator/2'); % mb
    safe_line(model_name, 'Grid_DQ_Controller/3', 'SBC_PWM_Generator/3'); % mc
    safe_line(model_name, 'Current_Sweep_MPPT/2', 'SBC_PWM_Generator/4');  % D0
    safe_line(model_name, 'SimClock/1', 'SBC_PWM_Generator/5');

    % PWM Generator Gate Pulses to Universal Bridge (6-pulse vector)
    safe_line(model_name, 'SBC_PWM_Generator/1', 'Universal_Bridge/1');

    % ---------------------------------------------------------------------
    % SCOPE MONITOR CONNECTIONS
    % ---------------------------------------------------------------------
    % Scope 1: PV Array (V_pv, I_pv, P_pv)
    safe_line(model_name, 'V_PV_meas/1', 'Scope_PV_Array/1');
    safe_line(model_name, 'I_PV_meas/1', 'Scope_PV_Array/2');
    safe_line(model_name, 'Current_Sweep_MPPT/4', 'Scope_PV_Array/3');

    % Scope 2: ZSI Dynamics (V_C1, V_dc)
    safe_line(model_name, 'V_C1_meas/1', 'Scope_ZSI_Dynamics/1');
    safe_line(model_name, 'V_dc_meas/1', 'Scope_ZSI_Dynamics/2');

    % Scope 3: MPPT Dynamics (P_pv, D0, state)
    safe_line(model_name, 'Current_Sweep_MPPT/4', 'Scope_MPPT_Dynamics/1');
    safe_line(model_name, 'Current_Sweep_MPPT/2', 'Scope_MPPT_Dynamics/2');
    safe_line(model_name, 'Current_Sweep_MPPT/3', 'Scope_MPPT_Dynamics/3');

    % Scope 4: 440V Grid Integration (V_grid, I_grid, P_grid, Q_grid)
    safe_line(model_name, 'Grid_VI_Meas/1', 'Scope_Grid_440V/1');
    safe_line(model_name, 'Grid_VI_Meas/2', 'Scope_Grid_440V/2');
    safe_line(model_name, 'Grid_DQ_Controller/4', 'Scope_Grid_440V/3'); % P_grid
    safe_line(model_name, 'Grid_DQ_Controller/5', 'Scope_Grid_440V/4'); % Q_grid

    % Save System
    save_system(model_name);
    fprintf('\n===================================================================\n');
    fprintf('SUCCESS: Simscape model successfully generated and saved to:\n');
    fprintf('         %s.slx\n', model_name);
    fprintf('===================================================================\n');
end

% -------------------------------------------------------------------------
% Helper Function: Add Simscape Block with Fallback and Newline Support
% -------------------------------------------------------------------------
function blk_h = add_sps_block(model, blk_name, sps_lib, powerlib_fallback, pos)
    target = [model '/' blk_name];
    sps_lib = strrep(sps_lib, '\n', newline);
    powerlib_fallback = strrep(powerlib_fallback, '\n', newline);
    
    lib_name = strtok(sps_lib, '/');
    try
        load_system(lib_name);
        blk_h = add_block(sps_lib, target, 'Position', pos);
    catch ME1
        try
            fb_lib = strtok(powerlib_fallback, '/');
            load_system(fb_lib);
            blk_h = add_block(powerlib_fallback, target, 'Position', pos);
        catch ME2
            fprintf('Warning loading block %s: %s (fallback: %s)\n', target, ME1.message, ME2.message);
        end
    end
end

% -------------------------------------------------------------------------
% Helper Function: Safe Line Router
% -------------------------------------------------------------------------
function safe_line(model, src, dst)
    try
        add_line(model, src, dst, 'autorouting', 'smart');
    catch
        try
            add_line(model, src, dst);
        catch ME
            fprintf('Notice connecting %s -> %s: %s\n', src, dst, ME.message);
        end
    end
end

% -------------------------------------------------------------------------
% Helper Function: Populate MATLAB Function Block Script via Stateflow
% -------------------------------------------------------------------------
function populate_matlab_function(blk_path, script_code)
    try
        sf = sfroot;
        chart = sf.find('Path', blk_path, '-isa', 'Stateflow.EMChart');
        if ~isempty(chart)
            chart.Script = script_code;
        end
    catch ME
        fprintf('Stateflow script assignment notice for %s: %s\n', blk_path, ME.message);
    end
end
