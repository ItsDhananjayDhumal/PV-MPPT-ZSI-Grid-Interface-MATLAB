% =========================================================================
% build_simulink_model.m
% =========================================================================
% Programmatically creates and wires the complete Simulink model:
% "pv_zsi_grid_mppt.slx"
%
% Architecture:
%   1. Environmental Inputs (Irradiance G, Temperature T, Step Profiler)
%   2. 10 kW PV Array Model Subsystem
%   3. Current Sweep MPPT Controller Subsystem (Periodic + Event-Driven)
%   4. Z-Source Inverter (ZSI) Impedance Network & Modulation Subsystem
%   5. 3-Phase Grid Interface (440V, 50Hz) & DQ Decoupled Vector Control
%   6. Multi-Channel Diagnostic Scopes & Performance Monitors
% =========================================================================

function build_simulink_model()
    model_name = 'pv_zsi_grid_mppt';
    
    fprintf('===================================================================\n');
    fprintf('Building Simulink Model: %s.slx ...\n', model_name);
    fprintf('===================================================================\n');
    
    % Initialize workspace parameters
    init_params;
    
    % Close if already open
    if bdIsLoaded(model_name)
        close_system(model_name, 0);
    end
    
    % Create new system
    new_system(model_name);
    open_system(model_name);
    
    % Configure Model Solver & Callbacks
    set_param(model_name, ...
        'Solver', 'ode23tb', ...
        'StopTime', '2.0', ...
        'MaxStep', '5e-5', ...
        'PreLoadFcn', 'init_params', ...
        'InitFcn', 'init_params');
    
    fprintf('Configuring subsystems and wiring blocks...\n');
    
    % ---------------------------------------------------------------------
    % 1. Environmental Inputs Block
    % ---------------------------------------------------------------------
    % Clock
    add_block('simulink/Sources/Clock', [model_name '/SimClock'], ...
        'Position', [40, 160, 70, 180]);
    
    % Irradiance Source (Step / Constant)
    add_block('simulink/Sources/Constant', [model_name '/Irradiance_G'], ...
        'Value', '1000', ...
        'Position', [40, 60, 100, 90]);
    
    % Temperature Source
    add_block('simulink/Sources/Constant', [model_name '/Temperature_T'], ...
        'Value', '25', ...
        'Position', [40, 110, 100, 140]);
        
    % ---------------------------------------------------------------------
    % 2. Current Sweep MPPT Controller Block (MATLAB Function)
    % ---------------------------------------------------------------------
    mppt_blk = [model_name '/Current_Sweep_MPPT_Controller'];
    add_block('simulink/User-Defined Functions/MATLAB Function', mppt_blk, ...
        'Position', [280, 80, 430, 180]);
        
    % Script inside the MPPT MATLAB Function block
    mppt_code = sprintf([...
        'function [I_ref, D0, state] = Current_Sweep_MPPT_Controller(V_pv, I_pv, t)\n', ...
        '%% Current Sweep MPPT with Periodic and Event-Driven Triggers\n', ...
        'persistent sm_state sweep_start_time t_last_sweep P_max_found I_mpp_found V_mpp_found P_hold_prev dP_counter I_ref_cur D0_cur\n\n', ...
        'if isempty(sm_state)\n', ...
        '    sm_state = 1;\n', ...
        '    sweep_start_time = t;\n', ...
        '    t_last_sweep = t;\n', ...
        '    P_max_found = 0;\n', ...
        '    I_mpp_found = 27.9;\n', ...
        '    V_mpp_found = 382.9;\n', ...
        '    P_hold_prev = 10680;\n', ...
        '    dP_counter = 0;\n', ...
        '    I_ref_cur = 0.5;\n', ...
        '    D0_cur = 0.30;\n', ...
        'end\n\n', ...
        'P_inst = V_pv * I_pv;\n', ...
        'V_dc_target = 950.0;\n', ...
        'T_sweep = 0.040; %% 40 ms sweep duration\n', ...
        'T_period = 0.800; %% 800 ms periodic interval\n', ...
        'dP_thresh = 0.05; %% 5%% relative power variation threshold\n\n', ...
        'if sm_state == 1\n', ...
        '    %% STATE 1: ACTIVE CURRENT SWEEP\n', ...
        '    t_el = t - sweep_start_time;\n', ...
        '    if t_el <= T_sweep\n', ...
        '        I_ref_cur = 0.5 + (t_el / T_sweep) * (32.0 - 0.5);\n', ...
        '        if P_inst > P_max_found && V_pv > 10.0\n', ...
        '            P_max_found = P_inst;\n', ...
        '            I_mpp_found = I_pv;\n', ...
        '            V_mpp_found = V_pv;\n', ...
        '        end\n', ...
        '        D0_cur = 0.30;\n', ...
        '    else\n', ...
        '        sm_state = 2; %% Transition to HOLD\n', ...
        '        if P_max_found < 50.0\n', ...
        '            P_max_found = 100.0;\n', ...
        '            I_mpp_found = 1.0;\n', ...
        '            V_mpp_found = 380.0;\n', ...
        '        end\n', ...
        '        I_ref_cur = I_mpp_found;\n', ...
        '        P_hold_prev = P_max_found;\n', ...
        '        t_last_sweep = t;\n', ...
        '        dP_counter = 0;\n', ...
        '        B_opt = max(1.1, min(4.0, V_dc_target / max(50.0, V_mpp_found)));\n', ...
        '        D0_cur = max(0.08, min(0.33, (B_opt - 1) / (2 * B_opt)));\n', ...
        '    end\n', ...
        'else\n', ...
        '    %% STATE 2: HOLD / TRACK\n', ...
        '    I_ref_cur = I_mpp_found;\n', ...
        '    if (t - t_last_sweep) >= T_period\n', ...
        '        sm_state = 1;\n', ...
        '        sweep_start_time = t;\n', ...
        '        P_max_found = 0;\n', ...
        '    else\n', ...
        '        rel_dP = abs(P_inst - P_hold_prev) / max(200.0, P_hold_prev);\n', ...
        '        if rel_dP > dP_thresh\n', ...
        '            dP_counter = dP_counter + 1;\n', ...
        '            if dP_counter >= 3\n', ...
        '                sm_state = 1;\n', ...
        '                sweep_start_time = t;\n', ...
        '                P_max_found = 0;\n', ...
        '                dP_counter = 0;\n', ...
        '            end\n', ...
        '        else\n', ...
        '            dP_counter = max(0, dP_counter - 1);\n', ...
        '            P_hold_prev = 0.98 * P_hold_prev + 0.02 * P_inst;\n', ...
        '        end\n', ...
        '    end\n', ...
        'end\n\n', ...
        'I_ref = I_ref_cur;\n', ...
        'D0 = D0_cur;\n', ...
        'state = sm_state;\n', ...
        'end\n' ...
    ]);
    
    % Populate MATLAB Function block content via Stateflow/Simulink API
    try
        sf = sfroot;
        mppt_chart = sf.find('Path', mppt_blk, '-isa', 'Stateflow.EMChart');
        if ~isempty(mppt_chart)
            mppt_chart.Script = mppt_code;
        end
    catch ME
        fprintf('Note: Script assignment via Stateflow API: %s\n', ME.message);
    end
    
    % ---------------------------------------------------------------------
    % 3. PV Array Subsystem Block (Mathematical Single-Diode Model)
    % ---------------------------------------------------------------------
    pv_blk = [model_name '/PV_Array_10kW'];
    add_block('simulink/User-Defined Functions/MATLAB Function', pv_blk, ...
        'Position', [140, 60, 240, 160]);
    pv_code = sprintf([...
        'function [V_pv, I_pv, P_pv] = PV_Array_10kW(G, T, I_ref)\n', ...
        '%% 10 kW High-Efficiency PV Array Model\n', ...
        'persistent i_pv_act\n', ...
        'if isempty(i_pv_act)\n', ...
        '    i_pv_act = 5.0;\n', ...
        'end\n', ...
        '%% Filter dynamic current response\n', ...
        'tau = 1.0e-3;\n', ...
        'dt = 5.0e-5;\n', ...
        'i_pv_act = i_pv_act + (dt / tau) * (I_ref - i_pv_act);\n', ...
        'i_pv_act = max(0.0, min(32.0, i_pv_act));\n', ...
        'I_pv = i_pv_act;\n\n', ...
        '%% Array Equivalent Single-Diode Representation\n', ...
        'N_ser = 7; N_par = 5; N_cells = 96;\n', ...
        'Iph = N_par * 5.96 * (G / 1000.0) * (1 + 0.0035*(T - 25));\n', ...
        'I0 = N_par * 1.5e-9 * ((T + 273.15)/298.15)^3;\n', ...
        'Vt = (N_ser * N_cells * 1.38e-23 * (T + 273.15)) / 1.602e-19;\n', ...
        'Rs = 0.25 * (N_ser / N_par);\n', ...
        'Rsh = 1500.0 * (N_ser / N_par);\n\n', ...
        '%% Solve terminal voltage\n', ...
        'i_val = min(I_pv, Iph * 0.999);\n', ...
        'v_val = max(0.0, (N_ser * 64.2) * (1 - (i_val / max(1e-2, Iph))^2));\n', ...
        'for iter = 1:5\n', ...
        '    f = Iph - I0 * (exp((v_val + i_val*Rs)/(1.25*Vt)) - 1) - (v_val + i_val*Rs)/Rsh - i_val;\n', ...
        '    df = - (I0/(1.25*Vt))*exp((v_val + i_val*Rs)/(1.25*Vt)) - 1/Rsh;\n', ...
        '    step = f / df;\n', ...
        '    v_val = max(0.0, v_val - step);\n', ...
        'end\n', ...
        'V_pv = v_val;\n', ...
        'P_pv = V_pv * I_pv;\n', ...
        'end\n' ...
    ]);
    try
        sf = sfroot;
        pv_chart = sf.find('Path', pv_blk, '-isa', 'Stateflow.EMChart');
        if ~isempty(pv_chart)
            pv_chart.Script = pv_code;
        end
    catch
    end

    % ---------------------------------------------------------------------
    % 4. Z-Source Inverter (ZSI) Subsystem Block
    % ---------------------------------------------------------------------
    zsi_blk = [model_name '/Z_Source_Inverter_Network'];
    add_block('simulink/User-Defined Functions/MATLAB Function', zsi_blk, ...
        'Position', [480, 80, 620, 200]);
    zsi_code = sprintf([...
        'function [Vdc_peak, Vc, iL, B_boost] = Z_Source_Inverter_Network(V_pv, P_pv, D0)\n', ...
        '%% Dynamic Averaged ZSI Impedance Network\n', ...
        'persistent v_c i_l\n', ...
        'if isempty(v_c)\n', ...
        '    v_c = 450.0;\n', ...
        '    i_l = 10.0;\n', ...
        'end\n', ...
        'Lz = 3.5e-3; Cz = 850e-6; rL = 0.04;\n', ...
        'dt = 5.0e-5;\n', ...
        'D0_eff = max(0.05, min(0.33, D0));\n', ...
        'B_boost = 1 / (1 - 2*D0_eff);\n', ...
        'Vdc_peak = max(V_pv, 2*v_c - V_pv);\n', ...
        'I_dc_inv = max(0.1, (P_pv * 0.965) / max(100.0, Vdc_peak));\n', ...
        'di_l = ((1 - D0_eff)*V_pv - (1 - 2*D0_eff)*v_c - rL*i_l) / Lz;\n', ...
        'dv_c = ((1 - 2*D0_eff)*i_l - (1 - D0_eff)*I_dc_inv) / Cz;\n', ...
        'i_l = max(0.0, i_l + di_l * dt);\n', ...
        'v_c = max(V_pv*0.5, v_c + dv_c * dt);\n', ...
        'Vc = v_c;\n', ...
        'iL = i_l;\n', ...
        'end\n' ...
    ]);
    try
        sf = sfroot;
        zsi_chart = sf.find('Path', zsi_blk, '-isa', 'Stateflow.EMChart');
        if ~isempty(zsi_chart)
            zsi_chart.Script = zsi_code;
        end
    catch
    end

    % ---------------------------------------------------------------------
    % 5. 3-Phase 440V Grid Interface & DQ Control Subsystem
    % ---------------------------------------------------------------------
    grid_blk = [model_name '/Grid_Interface_440V_50Hz'];
    add_block('simulink/User-Defined Functions/MATLAB Function', grid_blk, ...
        'Position', [670, 80, 820, 220]);
    grid_code = sprintf([...
        'function [P_grid, Q_grid, PF, v_ga, i_ga] = Grid_Interface_440V_50Hz(P_pv, Vdc_peak, t)\n', ...
        '%% Synchronous DQ Decoupled Inverter & Grid Integration\n', ...
        'persistent i_d i_q int_d int_q\n', ...
        'if isempty(i_d)\n', ...
        '    i_d = 0.0; i_q = 0.0; int_d = 0.0; int_q = 0.0;\n', ...
        'end\n', ...
        'dt = 5.0e-5;\n', ...
        'V_LL_rms = 440.0; f_g = 50.0; omega = 2*pi*f_g;\n', ...
        'V_ph_peak = (V_LL_rms / sqrt(3)) * sqrt(2); %% 359.26 V\n', ...
        'Lf = 4.5e-3; Rf = 0.15;\n', ...
        '%% References\n', ...
        'P_ac_target = max(50.0, P_pv * 0.965);\n', ...
        'id_ref = (2/3) * (P_ac_target / V_ph_peak);\n', ...
        'iq_ref = 0.0; %% Unity Power Factor\n', ...
        'err_d = id_ref - i_d;\n', ...
        'err_q = iq_ref - i_q;\n', ...
        'int_d = int_d + err_d * dt;\n', ...
        'int_q = int_q + err_q * dt;\n', ...
        'Kp = 22.6; Ki = 250.0;\n', ...
        'vd_cmd = V_ph_peak + Rf*i_d - omega*Lf*i_q + Kp*err_d + Ki*int_d;\n', ...
        'vq_cmd = Rf*i_q + omega*Lf*i_d + Kp*err_q + Ki*int_q;\n', ...
        'did = (vd_cmd - V_ph_peak - Rf*i_d + omega*Lf*i_q) / Lf;\n', ...
        'diq = (vq_cmd - Rf*i_q - omega*Lf*i_d) / Lf;\n', ...
        'i_d = i_d + did * dt;\n', ...
        'i_q = i_q + diq * dt;\n', ...
        'P_grid = (3/2) * V_ph_peak * i_d;\n', ...
        'Q_grid = -(3/2) * V_ph_peak * i_q;\n', ...
        'S_grid = sqrt(P_grid^2 + Q_grid^2);\n', ...
        'if S_grid > 10.0, PF = P_grid / S_grid; else, PF = 1.0; end\n', ...
        'theta = omega * t;\n', ...
        'v_ga = V_ph_peak * sin(theta);\n', ...
        'i_ga = i_d * sin(theta) + i_q * cos(theta);\n', ...
        'end\n' ...
    ]);
    try
        sf = sfroot;
        grid_chart = sf.find('Path', grid_blk, '-isa', 'Stateflow.EMChart');
        if ~isempty(grid_chart)
            grid_chart.Script = grid_code;
        end
    catch
    end

    % ---------------------------------------------------------------------
    % 6. Diagnostic Scopes
    % ---------------------------------------------------------------------
    add_block('simulink/Sinks/Scope', [model_name '/Scope_PV_Tracking'], ...
        'NumInputPorts', '3', 'Position', [480, 20, 520, 70]);
    add_block('simulink/Sinks/Scope', [model_name '/Scope_ZSI_Dynamics'], ...
        'NumInputPorts', '4', 'Position', [670, 20, 710, 70]);
    add_block('simulink/Sinks/Scope', [model_name '/Scope_Grid_Powers'], ...
        'NumInputPorts', '3', 'Position', [870, 70, 910, 120]);
    add_block('simulink/Sinks/Scope', [model_name '/Scope_Grid_Waveforms'], ...
        'NumInputPorts', '2', 'Position', [870, 150, 910, 200]);

    % Feedback Delay to cleanly break algebraic loop between PV and MPPT
    add_block('simulink/Discrete/Unit Delay', [model_name '/UnitDelay_Iref'], ...
        'InitialCondition', '0.5', 'SampleTime', '5e-5', ...
        'Position', [220, 220, 250, 250]);

    % ---------------------------------------------------------------------
    % 7. Interconnecting Signal Lines
    % ---------------------------------------------------------------------
    % Environmental inputs -> PV Array
    add_line(model_name, 'Irradiance_G/1', 'PV_Array_10kW/1', 'autorouting', 'on');
    add_line(model_name, 'Temperature_T/1', 'PV_Array_10kW/2', 'autorouting', 'on');
    add_line(model_name, 'UnitDelay_Iref/1', 'PV_Array_10kW/3', 'autorouting', 'on');

    % PV Array -> MPPT Controller
    add_line(model_name, 'PV_Array_10kW/1', 'Current_Sweep_MPPT_Controller/1', 'autorouting', 'on');
    add_line(model_name, 'PV_Array_10kW/2', 'Current_Sweep_MPPT_Controller/2', 'autorouting', 'on');
    add_line(model_name, 'SimClock/1', 'Current_Sweep_MPPT_Controller/3', 'autorouting', 'on');

    % MPPT Controller I_ref -> Unit Delay (feedback)
    add_line(model_name, 'Current_Sweep_MPPT_Controller/1', 'UnitDelay_Iref/1', 'autorouting', 'on');

    % PV Array & MPPT -> ZSI
    add_line(model_name, 'PV_Array_10kW/1', 'Z_Source_Inverter_Network/1', 'autorouting', 'on');
    add_line(model_name, 'PV_Array_10kW/3', 'Z_Source_Inverter_Network/2', 'autorouting', 'on');
    add_line(model_name, 'Current_Sweep_MPPT_Controller/2', 'Z_Source_Inverter_Network/3', 'autorouting', 'on');

    % ZSI & PV -> Grid Interface
    add_line(model_name, 'PV_Array_10kW/3', 'Grid_Interface_440V_50Hz/1', 'autorouting', 'on');
    add_line(model_name, 'Z_Source_Inverter_Network/1', 'Grid_Interface_440V_50Hz/2', 'autorouting', 'on');
    add_line(model_name, 'SimClock/1', 'Grid_Interface_440V_50Hz/3', 'autorouting', 'on');

    % Scope Connections
    add_line(model_name, 'PV_Array_10kW/3', 'Scope_PV_Tracking/1', 'autorouting', 'on');
    add_line(model_name, 'PV_Array_10kW/1', 'Scope_PV_Tracking/2', 'autorouting', 'on');
    add_line(model_name, 'PV_Array_10kW/2', 'Scope_PV_Tracking/3', 'autorouting', 'on');

    add_line(model_name, 'Z_Source_Inverter_Network/1', 'Scope_ZSI_Dynamics/1', 'autorouting', 'on');
    add_line(model_name, 'Z_Source_Inverter_Network/2', 'Scope_ZSI_Dynamics/2', 'autorouting', 'on');
    add_line(model_name, 'Z_Source_Inverter_Network/3', 'Scope_ZSI_Dynamics/3', 'autorouting', 'on');
    add_line(model_name, 'Z_Source_Inverter_Network/4', 'Scope_ZSI_Dynamics/4', 'autorouting', 'on');

    add_line(model_name, 'Grid_Interface_440V_50Hz/1', 'Scope_Grid_Powers/1', 'autorouting', 'on');
    add_line(model_name, 'Grid_Interface_440V_50Hz/2', 'Scope_Grid_Powers/2', 'autorouting', 'on');
    add_line(model_name, 'Grid_Interface_440V_50Hz/3', 'Scope_Grid_Powers/3', 'autorouting', 'on');

    add_line(model_name, 'Grid_Interface_440V_50Hz/4', 'Scope_Grid_Waveforms/1', 'autorouting', 'on');
    add_line(model_name, 'Grid_Interface_440V_50Hz/5', 'Scope_Grid_Waveforms/2', 'autorouting', 'on');

    % Save model
    save_system(model_name, [model_name '.slx']);
    fprintf('Simulink model successfully constructed and saved to: %s.slx\n', model_name);
    fprintf('===================================================================\n');
end
